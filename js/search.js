/**
 * search.js — YouTube and SoundCloud track & playlist search.
 *
 * Handles:
 * - Track search via YouTube Data API v3 + SoundCloud (through api/soundcloud.php)
 * - Direct link detection (youtube.com/watch, soundcloud.com/…, on.soundcloud.com/…)
 * - Playlist/import search via YouTube + SoundCloud
 * - Search source toggle buttons (#ytsearchSelect, #scsearchSelect)
 * - Import source toggle tabs
 */

// ─── YouTube API Helper ──────────────────────────────────────────────────────

/**
 * Call the YouTube Data API v3 directly via AJAX.
 * Avoids gapi client entirely — no discovery loading, no Promise conflicts.
 * @param {string}   resource - API resource path (e.g. 'search', 'videos', 'playlistItems')
 * @param {Object}   params   - Query parameters (key is added automatically)
 * @param {Function} callback - Called with the raw API response object
 */
function ytAPI(resource, params, callback) {
  params.key = ftconfigs.youtubeKey;
  $.ajax({
    url: 'https://www.googleapis.com/youtube/v3/' + resource,
    data: params,
    type: 'GET',
    dataType: 'json',
    success: callback,
    error: function (xhr) {
      var msg = (xhr.responseJSON && xhr.responseJSON.error)
        ? xhr.responseJSON.error.code + ' ' + xhr.responseJSON.error.message
        : xhr.status + ' ' + xhr.statusText;
      console.error('YouTube API error:', msg, xhr.responseJSON || xhr.responseText);
      callback({ items: [] });
    }
  });
}

/**
 * Extract a query-string parameter value from a URL string.
 * @param {string} str - Full URL
 * @param {string} key - Parameter name
 * @returns {string} Decoded parameter value (or empty string)
 */
function getQueryStringValue(str, key) {
  return unescape(
    str.replace(
      new RegExp("^(?:.*[&\\?]" + escape(key).replace(/[\.\+\*]/g, "\\$&") + "(?:\\=([^&]*))?)?.*$", "i"),
      "$1"
    )
  );
}

// ─── Ranking YouTube results ─────────────────────────────────────────────────

/** Lowercase letters and digits only, without a leading "the": names compare loosely. */
var ytNameKey = function (s) {
  return String(s || "").toLowerCase().replace(/^the\s+/, "").replace(/[^a-z0-9]+/g, "");
};

// Not the music video, though the artist put it up (as the hostbot ranks them, lib/swaps.js videoRank)
var YT_NOT_THE_VIDEO = /\b(?:lyrics?|lyric video|visuali[sz]er|official audio|audio only|audio\)|full album|album stream|reaction|karaoke|cover|teaser|trailer|snippet|behind the scenes|making of|interview)\b/i;
var YT_THE_VIDEO = /\b(?:official (?:music )?video|music video|official mv|official hd video|official 4k video)\b/i;

/**
 * What a YouTube search result is, from its snippet: "audio" a YouTube Music
 * audio track; "video" the artist's official music video; "artist" another
 * video from the artist; "artist-other" the artist's lyric video, visualizer
 * or "Official Audio"; "other" anyone else's upload. The artist's own means
 * their channel ("Band", "Band Official", "BandVEVO") or any VEVO channel.
 * @param {Object} snippet - search.list / videos.list snippet
 * @param {string} [query] - what was searched for (its artist counts too)
 */
firetable.utilities.youtubeKind = function (snippet, query) {
  snippet = snippet || {};
  var channel = String(snippet.channelTitle || "");
  var title = firetable.ui.strip(String(snippet.title || ""));
  var desc = String(snippet.description || "");
  if (/ - Topic$/.test(channel) || /^\s*Provided to YouTube by /.test(desc) || /Auto-generated by YouTube\.?\s*$/.test(desc)) return "audio";
  var ck = ytNameKey(channel.replace(/VEVO$/i, "").replace(/\s+(?:official|music|records|tv)$/i, ""));
  var sep = title.indexOf(" - ");
  var tk = ytNameKey(sep > 0 ? title.slice(0, sep) : "");
  var qk = ytNameKey(query);
  var own = /VEVO$/i.test(channel) || (ck.length >= 2 && ((tk && (tk === ck || (ck.length >= 4 && (tk.indexOf(ck) !== -1 || ck.indexOf(tk) === 0)))) ||
    (ck.length >= 4 && qk.indexOf(ck) !== -1)));
  if (!own) return "other";
  if (YT_NOT_THE_VIDEO.test(title)) return "artist-other";
  return YT_THE_VIDEO.test(title) ? "video" : "artist";
};

/**
 * YouTube's results in the order that fits the list they're going to: for a
 * list kept to YouTube Music, audio tracks first; otherwise the artists'
 * official music videos first, then their other videos (and, for a list kept
 * to videos, audio tracks last). YouTube's own order holds within each kind.
 * @param {Array} items - search.list items
 * @param {string} format - the list's format ("ytm", "video", "sc" or "")
 * @param {string} [query]
 * @returns {Array<{item: Object, kind: string}>}
 */
firetable.utilities.rankYouTubeResults = function (items, format, query) {
  var order = format === "ytm" ? ["audio", "video", "artist", "artist-other", "other"]
    : format === "video" ? ["video", "artist", "artist-other", "other", "audio"]
    : ["video", "artist", "audio", "artist-other", "other"];
  return (items || []).map(function (item, i) {
    return { item: item, i: i, kind: firetable.utilities.youtubeKind(item && item.snippet, query) };
  }).sort(function (a, b) {
    return (order.indexOf(a.kind) - order.indexOf(b.kind)) || (a.i - b.i);
  }).map(function (x) { return { item: x.item, kind: x.kind }; });
};

/** The small mark a search result gets: what kind of upload it is ("" for none). */
var YT_KIND_LABELS = { audio: "YouTube Music", video: "Official video", artist: "Artist video" };

// ─── Track Search Setup ──────────────────────────────────────────────────────

/**
 * Bind the track search (#qsearch) and import search (#plMachine) keyup handlers.
 * Called once from firetable.ui.init().
 */
firetable.ui.setupSearchEvents = function () {
  var $searchItemTemplate = $('#searchResults .pvbar').remove();

  // Status line in a results box (text only, so messages can't inject HTML).
  var showStatus = function (sel, msg) {
    $(sel).empty().append($('<p class="searchStatus"></p>').text(msg));
  };

  // ── Shared helper: bind addtolist + queuetrack buttons on a search result row ──
  var bindSearchResultButtons = function ($srli, mediaCid, mediaType, extra) {
    extra = extra || {};
    $srli.attr('data-type', mediaType);
    firetable.ui.markSaved();
    $srli.find('.addtolist').on('click', function () {
      var listid = $("#listpicker").val();
      var title = $srli.find('.listwords').text();
      var refusal = firetable.utilities.formatRefusal(listid, mediaType);
      if (refusal) { firetable.ui.toast(refusal, "error"); return; }
      ftapi.actions.addTrackToTop(ftapi.lookup.listRef(listid), { type: mediaType, name: title, cid: mediaCid, img: extra.img, url: extra.url },
        firetable.preview, function (changePV) { if (changePV) firetable.preview = changePV; });
      var $fb = $srli.find('.search-feedback');
      $fb.text('added').addClass('visible');
      setTimeout(function () { $fb.removeClass('visible'); }, 2000);
    });

    $srli.find('.queuetrack').on('click', function () {
      var title = $srli.find('.listwords').text();
      firetable.actions.openStealPicker($(this), { cid: mediaCid, type: mediaType, title: title, img: extra.img, url: extra.url });
    });
  };

  // ── Track Search (Enter in #qsearch) ──
  $("#qsearch").on("keyup", function (e) {
    if (e.which !== 13) return;
    var txt = String($("#qsearch").val() || "").trim();
    if (!txt) return;
    var plLink = firetable.importer.parseLink(txt);
    if (plLink) { firetable.utilities.cancelSearchPreview(); return firetable.ui.offerImport('#searchResults', plLink); }
    var source = firetable.utilities.isSCLink(txt) ? MEDIA_SOUNDCLOUD : firetable.searchSelectsChoice;

    if (source === MEDIA_YOUTUBE) {
      // ── YouTube Track Search ──
      var showYTResults = function (response) {
        firetable.debug && console.log('queue search:', response);
        $('#searchResults').html("");
        firetable.utilities.cancelSearchPreview();

        // the artists' official videos first (audio tracks first for a list
        // kept to YouTube Music), each marked with what it is
        var ranked = firetable.utilities.rankYouTubeResults(response.items || [],
          firetable.utilities.listFormat($("#listpicker").val() || "0"), directLink ? "" : txt);
        $.each(ranked, function (index, r) {
          var item = r.item;
          var thecid = item.kind === "youtube#searchResult" ? item.id.videoId : item.id;
          var vidTitle = firetable.utilities.youtubeTrackName(item.snippet.title, item.snippet.channelTitle, item.snippet.description);
          var pkey = "ytcid" + thecid;

          var $srli = $searchItemTemplate.clone();
          $srli.attr('id', "pvbar" + pkey)
               .attr("data-key", pkey)
               .attr("data-cid", thecid);
          $srli.find('.q-art').css('background-image', 'url(https://img.youtube.com/vi/' + thecid + '/mqdefault.jpg)');
          $srli.find('.previewicon').attr('id', "pv" + pkey).on('click', function () {
            firetable.actions.pview($(this).closest('.pvbar').attr('data-key'), true, MEDIA_YOUTUBE);
          });
          // strip() decodes entities and drops tags (YouTube returns titles
          // HTML-escaped); .text() keeps the result from being parsed as HTML.
          $srli.find('.listwords').text(firetable.ui.strip(vidTitle));
          $srli.attr('data-kind', r.kind);
          if (YT_KIND_LABELS[r.kind]) $('<span class="search-kind"></span>').text(YT_KIND_LABELS[r.kind]).insertAfter($srli.find('.listwords'));
          $srli.find('.pvbarWrap').append('<a class="tracklink-btn" target="_blank" href="https://www.youtube.com/watch?v=' + thecid + '" title="Open on YouTube">' + YT_LOGO_SVG + '</a>');
          bindSearchResultButtons($srli, thecid, MEDIA_YOUTUBE);
          $("#searchResults").append($srli);
        });
      };

      // Check if it's a direct YouTube URL
      var directLink = false;
      var thecid = false;
      if (txt.match(/youtube.com\/watch/)) {
        thecid = getQueryStringValue(txt, "v");
        if (thecid) directLink = true;
      }

      if (directLink) {
        firetable.debug && console.log("direct yt link found");
        ytAPI('videos', { id: thecid, part: 'snippet', maxResults: 1 }, showYTResults);
      } else {
        $('#searchResults').html('<p class="searchStatus">Searching…</p>');
        ytAPI('search', { q: txt, type: 'video', part: 'snippet', maxResults: SEARCH_MAX_RESULTS }, showYTResults);
      }

    } else if (source === MEDIA_SOUNDCLOUD) {
      // ── SoundCloud Track Search ──
      var q = txt;

      var showSCResults = function (tracks) {
        firetable.debug && console.log('sc tracks:', tracks);
        $('#searchResults').html("");
        firetable.utilities.cancelSearchPreview();
        if (!tracks.length) {
          showStatus('#searchResults', 'No playable SoundCloud tracks found.');
          return;
        }

        $.each(tracks, function (index, item) {
          var parsed = firetable.utilities.parseArtistTitle(item.title, (item.user && item.user.username) || "");
          var vidTitle = parsed.artist + " - " + parsed.title;
          var pkey = "sccid" + item.id;

          var $srli = $searchItemTemplate.clone();
          $srli.attr('id', "pvbar" + pkey)
               .attr("data-key", pkey)
               .attr("data-cid", item.id);
          if (item.artwork_url) $srli.find('.q-art').css('background-image', 'url(' + item.artwork_url + ')');
          $srli.find('.previewicon').attr('id', "pv" + pkey).on('click', function () {
            firetable.actions.pview($(this).closest('.pvbar').attr('data-key'), true, MEDIA_SOUNDCLOUD);
          });
          $srli.find('.listwords').text(firetable.ui.strip(vidTitle));
          var $scLink = $('<a class="tracklink-btn" target="_blank" rel="noopener" title="Open on SoundCloud"></a>').html(SC_LOGO_SVG);
          if (/^https:\/\/(?:[a-z0-9-]+\.)?soundcloud\.com\//i.test(item.permalink_url || '')) $scLink.attr('href', item.permalink_url);
          $srli.find('.pvbarWrap').append($scLink);
          bindSearchResultButtons($srli, item.id, MEDIA_SOUNDCLOUD, firetable.utilities.soundCloudExtras(item));
          $("#searchResults").append($srli);
        });
      };

      var showSCError = function (err) {
        firetable.utilities.cancelSearchPreview();
        showStatus('#searchResults', err.message || "SoundCloud search failed.");
      };

      showStatus('#searchResults', 'Searching…');
      if (firetable.utilities.isSCLink(q)) {
        firetable.debug && console.log("sc direct link found");
        firetable.actions.resolveSCLink(q).then(function (item) {
          if (item && item.kind === "track") return showSCResults([item]);
          if (item && item.kind === "playlist") return firetable.ui.offerImport('#searchResults', { type: MEDIA_SOUNDCLOUD, url: q });
          showStatus('#searchResults', "That SoundCloud link isn't a track.");
        }, showSCError);
      } else {
        firetable.actions.scSearch('tracks', q).then(showSCResults, showSCError);
      }
    }
  });

  // ── Search Source Toggle Buttons ──
  // (a list kept to one source switches Find tracks to it: firetable.ui.matchSearchSource)
  $("#ytsearchSelect").on("click", function () {
    $("#scsearchSelect").removeClass("on").attr("aria-selected", "false");
    $(this).addClass("on").attr("aria-selected", "true");
    firetable.searchSelectsChoice = MEDIA_YOUTUBE;
  });
  $("#scsearchSelect").on("click", function () {
    $("#ytsearchSelect").removeClass("on").attr("aria-selected", "false");
    $(this).addClass("on").attr("aria-selected", "true");
    firetable.searchSelectsChoice = MEDIA_SOUNDCLOUD;
  });

  // ── Import Source Toggle (YouTube | SoundCloud) ──
  $("#ytimportchoice").on("click", function () { firetable.importSelectsChoice = MEDIA_YOUTUBE; });
  $("#scimportchoice").on("click", function () { firetable.importSelectsChoice = MEDIA_SOUNDCLOUD; });
  $("#importSources .tab").on("click", function () {
    $(this).siblings().removeClass('on').attr('aria-pressed', 'false');
    $(this).addClass('on').attr('aria-pressed', 'true');
    $("#importResults").html("");
    $("#plMachine").trigger("focus");
  });

  // ── Import result rows ──
  // Text nodes only, so playlist titles from YouTube/SoundCloud can't inject
  // HTML. The row opens the playlist's songs (step 2); nothing is added yet.
  var appendImportResult = function (meta) {
    var $row = $('<div class="importResult"></div>').attr('data-id', meta.id);
    var $open = $('<button type="button" class="im-open"></button>')
      .attr('aria-label', 'See the songs in ' + meta.name)
      .on('click', function () { firetable.importer.show(meta); });
    $('<span class="imtxt"></span>').text(meta.name).appendTo($open);
    $('<span class="im-by"></span>').text([meta.by ? 'by ' + meta.by : '', typeof meta.count === 'number' ? firetable.utilities.pluralize(meta.count, 'song') : ''].filter(Boolean).join(' · ')).appendTo($open);
    $open.append('<i class="material-symbols-outlined" aria-hidden="true">chevron_right</i>');
    $row.append($open);
    var platform = meta.type === MEDIA_SOUNDCLOUD ? 'SoundCloud' : 'YouTube';
    var $link = $('<a target="_blank" rel="noopener" class="importLinkCheck"></a>')
      .attr({ title: 'Open on ' + platform, 'aria-label': 'Open on ' + platform })
      .html(meta.type === MEDIA_SOUNDCLOUD ? SC_LOGO_SVG : YT_LOGO_SVG);
    if (/^https:\/\//i.test(meta.href || '')) $link.attr('href', meta.href);
    $row.append($link);
    $("#importResults").append($row);
    return $row;
  };

  // ── Playlist/Import Search (#plMachine) ──
  $("#plMachine").on("keyup", function (e) {
    if (e.which !== 13) return;
    var val = String($("#plMachine").val() || "").trim();
    if (!val) return;
    $("#importResults").html("");
    var link = firetable.importer.parseLink(val);
    var searchFrom = link ? link.type : firetable.importSelectsChoice;
    if (link) {
      $(link.type === MEDIA_SOUNDCLOUD ? "#scimportchoice" : "#ytimportchoice").addClass('on').attr('aria-pressed', 'true')
        .siblings().removeClass('on').attr('aria-pressed', 'false');
      firetable.importSelectsChoice = link.type;
      showStatus('#importResults', 'Looking it up…');
      firetable.importer.peek(link).then(function (meta) {
        $("#importResults").html("");
        if (!meta) return showStatus('#importResults', link.type === MEDIA_SOUNDCLOUD ? "That link isn't a public SoundCloud playlist." : "That playlist isn't public, or it's gone.");
        appendImportResult(meta);
        firetable.importer.show(meta);
      });
      return;
    }

    if (searchFrom === MEDIA_YOUTUBE) {
      // a search costs 100 of the day's YouTube units: say it's under way
      showStatus('#importResults', 'Searching YouTube…');
      ytAPI('search', { q: val, type: 'playlist', part: 'snippet', maxResults: SEARCH_MAX_RESULTS }, function (response) {
        $("#importResults").html("");
        var items = response.items || [];
        if (!items.length) return showStatus('#importResults', 'No YouTube playlists found.');
        var rows = {};
        $.each(items, function (index, item) {
          var id = item.id && item.id.playlistId;
          if (!id) return;
          var meta = {
            type: MEDIA_YOUTUBE, id: id,
            name: firetable.ui.strip(item.snippet.title), by: firetable.ui.strip(item.snippet.channelTitle || ''), count: null,
            href: 'https://www.youtube.com/playlist?list=' + encodeURIComponent(id)
          };
          rows[id] = { meta: meta, $row: appendImportResult(meta) };
        });
        // how many songs each has: 1 unit for all of them
        ytAPI('playlists', { id: Object.keys(rows).join(','), part: 'contentDetails', maxResults: 50 }, function (res) {
          $.each(res.items || [], function (i, pl) {
            var r = rows[pl.id];
            if (!r || !pl.contentDetails) return;
            r.meta.count = pl.contentDetails.itemCount;
            r.$row.find('.im-by').text([r.meta.by ? 'by ' + r.meta.by : '', firetable.utilities.pluralize(r.meta.count, 'song')].filter(Boolean).join(' · '));
          });
        });
      });

    } else if (searchFrom === MEDIA_SOUNDCLOUD) {
      showStatus('#importResults', 'Searching SoundCloud…');
      firetable.actions.scSearch('playlists', val).then(function (lists) {
        $("#importResults").html("");
        lists = $.map(lists, function (item) { return firetable.importer.fromSoundCloud(item); });
        if (!lists.length) return showStatus('#importResults', 'No public SoundCloud playlists found.');
        $.each(lists, function (i, meta) { appendImportResult(meta); });
      }, function (err) {
        showStatus('#importResults', err.message || "SoundCloud search failed.");
      });
    }
  });

  firetable.importer.init();
};

/**
 * "That's a playlist: [name] · N songs. Import it" in a results box, for a
 * playlist link pasted where a song was expected.
 * @param {string} sel - the results box
 * @param {Object} link - firetable.importer.parseLink's result
 */
firetable.ui.offerImport = function (sel, link) {
  var $box = $(sel).empty().append($('<p class="searchStatus"></p>').text("That's a playlist. Looking it up…"));
  firetable.importer.peek(link).then(function (meta) {
    $box.empty();
    if (!meta) {
      $box.append($('<p class="searchStatus"></p>').text("That's a playlist link, but it isn't public or it's gone."));
      return;
    }
    var $p = $('<p class="searchStatus im-offer"></p>').text("That's a playlist: " + firetable.importer.describe(meta) + ". ");
    $('<button type="button" class="butt im-offerGo">Import it</button>')
      .on('click', function () { firetable.importer.open(meta); })
      .appendTo($p);
    $box.append($p);
  });
};

/**
 * Point Find tracks at the source a list is kept to: SoundCloud for a
 * SoundCloud list, YouTube for one kept to YouTube Music or videos. A list
 * that takes any source leaves the choice as it is.
 * @param {string} listID
 */
firetable.ui.matchSearchSource = function (listID) {
  var f = firetable.utilities.listFormat(listID);
  if (!f) return;
  var want = f === "sc" ? "#scsearchSelect" : "#ytsearchSelect";
  if (!$(want).hasClass("on")) $(want).trigger("click");
};
